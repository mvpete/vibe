using System.Text.Json.Nodes;

namespace Vibec.Tests;

public class StaticPassTests
{
    [Theory]
    [InlineData("int x = \"42\"", "int x = 42")]
    [InlineData("float x = \"2.5\"", "float x = 2.5")]
    [InlineData("bool x = \"yes\"", "bool x = true")]
    [InlineData("int x = 2.6", "int x = 3")]
    [InlineData("string x = 7", "string x = \"7\"")]
    [InlineData("int x = true", "int x = 1")]
    [InlineData("list<int> x = 5", "list<int> x = [5]")]
    public void ObviousCoercionsFoldWithoutAsking(string src, string expected)
    {
        var (program, pass) = Vibe.Analyze(src);
        Assert.Empty(pass.Questions);
        Assert.Equal(expected, Printer.Print(program).Trim());
    }

    [Fact]
    public void MeaningfulLiteralsBecomeQuestions()
    {
        var (_, pass) = Vibe.Analyze("int five = \"five\"");
        var q = Assert.Single(pass.Questions);
        Assert.Equal(QuestionKind.Coerce, q.Kind);
        Assert.Equal("int", q.To!.ToString());
    }

    [Fact]
    public void AnswersFoldIntoTheProgram()
    {
        var key = Knowledge.CoerceKey(JsonValue.Create("five"), VType.Int, null);
        var (program, pass) = Vibe.Analyze("int five = \"five\"", Vibe.Knows((key, Vibe.Value(5))));
        Assert.Empty(pass.Questions);
        Assert.StartsWith("int five = 5", Printer.Print(program));
    }

    [Fact]
    public void AnAnswerOfTheWrongTypeIsDeferred()
    {
        var key = Knowledge.CoerceKey(JsonValue.Create("five"), VType.Int, null);
        var (program, pass) = Vibe.Analyze("int five = \"five\"", Vibe.Knows((key, Vibe.Value("not a number"))));
        Assert.Contains("vibe<int>(\"five\")", Printer.Print(program));
        Assert.Contains("deferred", pass.Features);
    }

    [Fact]
    public void RuntimeValuesCoerceAtRuntime()
    {
        var (program, pass) = Vibe.Analyze("string s = ask()\nint n = s");
        Assert.Empty(pass.Questions);
        Assert.Contains("runtime-coercion", pass.Features);
        Assert.Contains("int n = vibe<int>(s)", Printer.Print(program));
    }

    [Fact]
    public void UndefinedFunctionsAskWithTheExpectedReturnType()
    {
        var (_, pass) = Vibe.Analyze("int lucky = GenerateLuckyNumber()");
        var q = Assert.Single(pass.Questions);
        Assert.Equal(QuestionKind.Function, q.Kind);
        Assert.Equal("int", q.Expected!.ToString());
    }

    [Fact]
    public void GeneratedFunctionsAreAdoptedAndChecked()
    {
        var key = Knowledge.FunctionKey("GenerateLuckyNumber", [], VType.Int);
        var answer = new Answer { Ok = true, Returns = "int", Source = "int GenerateLuckyNumber() { return 7 }" };
        var (program, pass) = Vibe.Analyze("int lucky = GenerateLuckyNumber()", Vibe.Knows((key, answer)));

        var fn = Assert.Single(pass.Generated);
        Assert.True(fn.Generated);
        Assert.Contains(pass.Warnings(), w => w.Contains("vibed one up"));
        Assert.Contains("# generated by the vibe pass", Printer.Print(program.Concat(pass.Generated)));
    }

    [Fact]
    public void UndeclaredWordsAskWithTheirContext()
    {
        var (_, pass) = Vibe.Analyze("while infinity { break }");
        var q = Assert.Single(pass.Questions);
        Assert.Equal(QuestionKind.Name, q.Kind);
        Assert.Equal("bool", q.Expected!.ToString());
    }

    [Fact]
    public void UndeclaredWordsResolveToConstants()
    {
        var key = Knowledge.NameKey("infinity", [], VType.Bool);
        var (program, _) = Vibe.Analyze("while infinity { break }", Vibe.Knows((key, Vibe.Value(true))));
        Assert.StartsWith("while true", Printer.Print(program));
    }

    [Fact]
    public void TyposGetFixed()
    {
        var key = Knowledge.NameKey("lukcy", ["lucky"], null);
        var (program, pass) = Vibe.Analyze("int lucky = 7\nprint lukcy", Vibe.Knows((key, new Answer { Ok = true, Rename = "lucky" })));
        Assert.Contains("print(lucky)", Printer.Print(program));
        Assert.Contains(pass.Warnings(), w => w.Contains("vibed it to 'lucky'"));
    }

    [Fact]
    public void UnresolvedNamesAreErrorsInTheFinalRound()
    {
        var (_, pass) = Vibe.Analyze("print nothing_here", final: true);
        Assert.Contains(pass.Errors(), e => e.Contains("isn't a thing"));
    }

    [Fact]
    public void ConstCannotBeReassigned()
    {
        var (_, pass) = Vibe.Analyze("based int max = 3\nmax = 4");
        Assert.Contains(pass.Errors(), e => e.Contains("is const"));
    }

    [Fact]
    public void GlobalsAreVisibleBeforeTheirDeclaration()
    {
        var (_, pass) = Vibe.Analyze("void bump() { glowup score }\nrentfree int score = 0");
        Assert.Empty(pass.Errors());
        Assert.Empty(pass.Questions);
    }

    [Fact]
    public void OnlyOneMainCharacter()
    {
        var (_, pass) = Vibe.Analyze("maincharacter { }\nmaincharacter { }");
        Assert.Contains(pass.Errors(), e => e.Contains("ensemble cast"));
    }

    [Fact]
    public void SleepDurationsAreResolvedAsSeconds()
    {
        var (_, pass) = Vibe.Analyze("touchgrass \"half a second\"");
        var q = Assert.Single(pass.Questions);
        Assert.Equal("a duration in seconds", q.Context);
    }

    [Fact]
    public void SwitchPatternsBendToTheSubject()
    {
        var (program, _) = Vibe.Analyze("int n = 1\nswitch n {\n  \"1\" => print 1\n}");
        Assert.Contains("1 =>", Printer.Print(program));
    }

    [Fact]
    public void ReturnOutsideAFunctionIsAnError()
    {
        var (_, pass) = Vibe.Analyze("return");
        Assert.Contains(pass.Errors(), e => e.Contains("not in a function"));
    }

    [Fact]
    public void BareReturnEndsMainCharacter()
    {
        var (_, pass) = Vibe.Analyze("maincharacter { itsgiving }");
        Assert.Empty(pass.Errors());
    }
}
