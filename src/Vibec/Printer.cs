using System.Globalization;
using System.Text;

namespace Vibec;

/// Renders the annotated AST back to Vibe source: coercions resolved, typos fixed,
/// generated functions included, and a trailing `# ...` note wherever the compiler intervened.
public sealed class Printer
{
    readonly StringBuilder _out = new();
    readonly List<string> _notes = [];
    int _indent;

    public static string Print(IEnumerable<Stmt> program)
    {
        var p = new Printer();
        foreach (var s in program) p.Stmt(s);
        return p._out.ToString().TrimEnd() + "\n";
    }

    public static string Print(Expr e) => new Printer().E(e);

    void Line(string text)
    {
        _out.Append(new string(' ', _indent * 4)).Append(text);
        if (_notes.Count > 0) _out.Append("    # ").Append(string.Join("; ", _notes));
        _out.Append('\n');
        _notes.Clear();
    }

    void Block(string header, List<Stmt> body, string footer = "}")
    {
        Line(header + " {");
        _indent++;
        foreach (var s in body) Stmt(s);
        _indent--;
        Line(footer);
    }

    void Stmt(Stmt stmt)
    {
        switch (stmt)
        {
            case Decl d:
                var type = (d.Public ? "public " : "") + (d.Const ? "const " : "") + (d.Global ? "global " : "") + (d.DeclType == null ? "var" : d.DeclType.ToString());
                if (d.DeclType == null) _notes.Add($"inferred: {d.Resolved}");
                Line(d.Init == null ? $"{type} {d.Name}" : $"{type} {d.Name} = {T(d.Init)}");
                break;
            case Assign a:
                Line($"{T(a.Target)} {a.Op} {T(a.Value)}");
                break;
            case ExprStmt e:
                Line(T(e.Expr));
                break;
            case FnDecl fn:
                if (fn.Generated) Line("# generated by the vibe pass");
                if (fn.HasBody || fn.Body.Count > 0) Block(Sig(fn), fn.Body);
                else
                {
                    if (!fn.Native) _notes.Add("contract: the generator implements it");
                    Line(Sig(fn));
                }
                break;
            case UseStmt u:
                Line(u.Alias == null ? $"use {u.Module}" : $"use {u.Module} as {u.Alias}");
                break;
            case If i:
                IfChain(i, "if");
                break;
            case While w:
                Block($"while {T(w.Cond)}", w.Body);
                break;
            case For f:
                Block($"for {(f.DeclType != null ? f.DeclType + " " : "")}{f.Var} in {T(f.Iter)}", f.Body);
                break;
            case CFor cf:
                Block($"for ({(cf.Init != null ? Inline(cf.Init) : "")}; {(cf.Cond != null ? T(cf.Cond) : "")}; {(cf.Step != null ? Inline(cf.Step) : "")})", cf.Body);
                break;
            case Repeat r:
                Block($"repeat {T(r.Count)} times", r.Body);
                break;
            case Return r:
                Line(r.Value == null ? "return" : $"return {T(r.Value)}");
                break;
            case Say s:
                var args = ArgList(s.Args, s.Named);
                Line(s.Mode switch
                {
                    SayMode.Low => $"lowkey {args}",
                    SayMode.High => $"highkey {args}",
                    SayMode.Spill => $"spill {args}",
                    _ => $"print({args})",
                });
                break;
            case VibeCheck v:
                Line($"{(v.Assume ? "assume" : "vibecheck")} {T(v.Cond)}");
                break;
            case Throw th:
                Line($"throw {T(th.Value)}");
                break;
            case Exit ex:
                Line(ex.Code == null ? "exit" : $"exit {T(ex.Code)}");
                break;
            case Sleep sl:
                Line($"sleep {T(sl.Seconds)}");
                break;
            case Switch sw:
                Line($"switch {T(sw.Subject)} {{");
                _indent++;
                foreach (var arm in sw.Arms)
                    Block((arm.Patterns.Count == 0 ? "_" : string.Join(", ", arm.Patterns.Select(T))) + " =>", arm.Body);
                _indent--;
                Line("}");
                break;
            case MainBlock mb:
                Block("maincharacter", mb.Body);
                break;
            case TryCatch t:
                Line("try {");
                _indent++;
                foreach (var s in t.Body) Stmt(s);
                _indent--;
                Block($"}} catch ({t.ErrName})", t.Handler);
                break;
            case PromptStmt p:
                if (!p.Text.Contains('\n')) Line($"#prompt {p.Text}");
                else
                {
                    Line("#prompt {");
                    _indent++;
                    foreach (var l in p.Text.Split('\n')) Line(l);
                    _indent--;
                    Line("}");
                }
                break;
            case Break:
                Line("break");
                break;
            case Continue:
                Line("continue");
                break;
        }
    }

    void IfChain(If i, string keyword)
    {
        Line($"{keyword} {T(i.Cond)} {{");
        _indent++;
        foreach (var s in i.Then) Stmt(s);
        _indent--;
        if (i.Else == null) { Line("}"); return; }
        if (i.Else is [If nested]) { IfChain(nested, "} else if"); return; }
        Line("} else {");
        _indent++;
        foreach (var s in i.Else) Stmt(s);
        _indent--;
        Line("}");
    }

    public static string Signature(FnDecl fn) => new Printer().Sig(fn);

    /// A statement on one line, notes dropped (for a C-style for's init and step).
    static string Inline(Stmt s)
    {
        var p = new Printer();
        p.Stmt(s);
        var text = p._out.ToString().Trim();
        int note = text.IndexOf("    # ", StringComparison.Ordinal);
        return note >= 0 ? text[..note] : text;
    }

    string Sig(FnDecl fn)
    {
        var mods = (fn.Public ? "public " : "") + (fn.Native ? "native " : "");
        var ps = fn.Params.Select(p => p.Default == null ? $"{p.Type} {p.Name}" : $"{p.Type} {p.Name} = {E(p.Default)}");
        return $"{mods}{fn.Ret} {fn.Name}({string.Join(", ", ps)})";
    }

    string ArgList(List<Expr>? args, List<NamedArg> named) =>
        string.Join(", ", (args ?? []).Select(E).Concat(named.Select(n => $"{n.Name}: {E(n.Value)}")));

    /// Statement-level expression: no redundant outer parentheses.
    string T(Expr e)
    {
        var s = E(e);
        return e is Binary && s.StartsWith('(') && s.EndsWith(')') ? s[1..^1] : s;
    }

    string E(Expr e)
    {
        switch (e)
        {
            case Lit l: return l.Display ?? Value(l.Value);
            case ListLit list: return $"[{string.Join(", ", list.Items.Select(E))}]";
            case Interp interp:
                return "f\"" + string.Concat(interp.Parts.Select(p => p is string s
                    ? Escape(s).Replace("{", "{{").Replace("}", "}}")
                    : "{" + E((Expr)p) + "}")) + "\"";
            case Ident id:
                if (id.RenamedFrom != null) _notes.Add($"typo fixed: {id.RenamedFrom} → {id.Name}");
                return id.Name;
            case Unary u: return u.Op == "not" ? $"not {E(u.Operand)}" : $"-{E(u.Operand)}";
            case Binary b: return $"({E(b.Left)} {b.Op} {E(b.Right)})";
            case Call c:
                if (c.Meaning != null) _notes.Add($"{c.Name}: {c.Meaning}");
                return $"{c.Name}({ArgList(c.Args, c.Named)})";
            case Member m:
                if (m.Meaning != null) _notes.Add($"{(m.Module != null ? m.Module : "")}.{m.Name}: {m.Meaning}");
                return m.Args == null && m.Named.Count == 0 ? $"{E(m.Target)}.{m.Name}" : $"{E(m.Target)}.{m.Name}({ArgList(m.Args, m.Named)})";
            case Index ix: return $"{E(ix.Target)}[{E(ix.IndexExpr)}]";
            case IncDec inc: return inc.Prefix ? inc.Op + E(inc.Target) : E(inc.Target) + inc.Op;
            case Lambda lam:
                var ps = lam.Params.Count == 1 ? lam.Params[0] : $"({string.Join(", ", lam.Params)})";
                return $"{ps} => {E(lam.Body)}";
            case Ask a: return a.Prompt == null ? "ask()" : $"ask({E(a.Prompt)})";
            case VibeExpr v:
                if (v.Type != VType.Vibe) _notes.Add($"freeform → {v.Type}");
                return $"%{v.Text.Replace("%", "%%")}%";
            case Coerce c:
                var original = E(c.Inner);
                switch (c.Status)
                {
                    case CoerceStatus.Folded:
                        if (c.Source == "vibe") _notes.Add($"vibed from {original}" + (c.Why != null ? $" ({c.Why})" : ""));
                        return Value(c.Result);
                    case CoerceStatus.Deferred:
                        _notes.Add($"deferred: generator picks a {c.To} for {original}" + (c.Why != null ? $" ({c.Why})" : ""));
                        return $"vibe<{c.To}>({original})";
                    default:
                        _notes.Add($"runtime coercion → {c.To}");
                        return $"vibe<{c.To}>({original})";
                }
        }
        return "?";
    }

    static string Value(object? v) => v switch
    {
        null => "null",
        Maybe => "maybe",
        bool b => b ? "true" : "false",
        long n => n.ToString(CultureInfo.InvariantCulture),
        double d => d == Math.Floor(d) && Math.Abs(d) < 1e15 ? d.ToString("0.0", CultureInfo.InvariantCulture) : d.ToString("R", CultureInfo.InvariantCulture),
        string s => $"\"{Escape(s)}\"",
        List<object?> l => $"[{string.Join(", ", l.Select(Value))}]",
        _ => v.ToString() ?? "?",
    };

    static string Escape(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\t", "\\t");
}
